#!/usr/bin/env python3
"""Render scripts/effort/results/loc_table.md (and swap_delta.md) from JSON.

Usage:
  python scripts/effort/render_results.py
  python scripts/effort/render_results.py --from-count
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, Optional

EFFORT_ROOT = Path(__file__).resolve().parent
RESULTS = EFFORT_ROOT / "results"
sys.path.insert(0, str(EFFORT_ROOT))

from count_loc import CASES_ROOT, count_all  # noqa: E402
from compute_swap_delta import compute, render_md as render_swap_md  # noqa: E402


def _reduction(before: int, after: int) -> Optional[str]:
    if before <= 0:
        return None
    pct = 100.0 * (1.0 - (after / before))
    return f"{pct:.1f}%"


def render_loc_table(report: Dict[str, Any]) -> str:
    lines: list[str] = [
        "# Application effort LoC results",
        "",
        "Generated by `scripts/effort/count_loc.py` + `render_results.py`.",
        "Counting: non-blank, non-full-line-comment, non-docstring Python SLOC",
        "inside `@loc:boilerplate` / `@loc:core` regions. Nectar package internals",
        "are never counted. Cases with `effort_with` / `effort_without` in SPEC.md",
        "aggregate only those files.",
        "",
        "**Two outputs:** `loc_table.md` = size of each case’s primary With/Without",
        "scripts (B/C/T). `swap_delta.md` = lines that *change* when switching",
        "stack variants (A→B). Do not read C columns as swap edit cost.",
        "",
        "## Effort cases",
        "",
        "| Case | With B | With C | With T | Without B | Without C | Without T | B reduction | T reduction |",
        "|------|-------:|-------:|-------:|----------:|----------:|----------:|------------:|------------:|",
    ]
    swap_only: list[Dict[str, Any]] = []
    for case in report["cases"]:
        role = case.get("metric_role") or "effort"
        if role == "swap_only":
            swap_only.append(case)
            continue
        w = case.get("with") or {}
        wo = case.get("without") or {}
        wb, wc, wt = w.get("boilerplate", "—"), w.get("core", "—"), w.get("total", "—")
        ob, oc, ot = (
            wo.get("boilerplate", "—"),
            wo.get("core", "—"),
            wo.get("total", "—"),
        )
        b_red = "—"
        t_red = "—"
        if isinstance(wb, int) and isinstance(ob, int):
            b_red = _reduction(ob, wb) or "—"
        if isinstance(wt, int) and isinstance(ot, int):
            t_red = _reduction(ot, wt) or "—"
        lines.append(
            f"| `{case['id']}` | {wb} | {wc} | {wt} | {ob} | {oc} | {ot} | {b_red} | {t_red} |"
        )
    lines.append("")
    lines.append("B = boilerplate, C = core, T = total (B+C).")
    if swap_only:
        lines.extend(
            [
                "",
                "## Swap-only cases (diagnostic sizes; not T-reduction)",
                "",
                "Primary With/Without **file sizes** for cases whose main metric is",
                "interchange (`metric_role: swap_only`). B/C/T here are still LoC",
                "counts of Stack A scripts—not the A→B diff. For port cost see",
                "[`swap_delta.md`](swap_delta.md).",
                "",
                "| Case | With B | With C | With T | Without B | Without C | Without T |",
                "|------|-------:|-------:|-------:|----------:|----------:|----------:|",
            ]
        )
        for case in swap_only:
            w = case.get("with") or {}
            wo = case.get("without") or {}
            lines.append(
                f"| `{case['id']}` | {w.get('boilerplate', '—')} | {w.get('core', '—')} | "
                f"{w.get('total', '—')} | {wo.get('boilerplate', '—')} | "
                f"{wo.get('core', '—')} | {wo.get('total', '—')} |"
            )
        lines.append("")
        lines.append(
            "Core (C) can differ when one side inlines mission logic and the other "
            "puts helpers in boilerplate; that does not mean With costs more to port."
        )
    return "\n".join(lines).rstrip() + "\n"


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--from-count",
        action="store_true",
        help="Re-run count_loc and compute_swap_delta before rendering",
    )
    parser.add_argument("--cases-root", type=Path, default=CASES_ROOT)
    parser.add_argument("--json-in", type=Path, default=RESULTS / "loc_table.json")
    parser.add_argument("--md-out", type=Path, default=RESULTS / "loc_table.md")
    parser.add_argument("--swap-json", type=Path, default=RESULTS / "swap_delta.json")
    parser.add_argument("--swap-md-out", type=Path, default=RESULTS / "swap_delta.md")
    args = parser.parse_args(argv)

    if args.from_count:
        report = count_all(args.cases_root)
        args.json_in.parent.mkdir(parents=True, exist_ok=True)
        args.json_in.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        swap = compute()
        args.swap_json.write_text(json.dumps(swap, indent=2) + "\n", encoding="utf-8")
    elif args.json_in.is_file():
        report = json.loads(args.json_in.read_text(encoding="utf-8"))
        if args.swap_json.is_file():
            swap = json.loads(args.swap_json.read_text(encoding="utf-8"))
        else:
            swap = compute()
            args.swap_json.write_text(
                json.dumps(swap, indent=2) + "\n", encoding="utf-8"
            )
    else:
        report = count_all(args.cases_root)
        args.json_in.parent.mkdir(parents=True, exist_ok=True)
        args.json_in.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        swap = compute()
        args.swap_json.write_text(json.dumps(swap, indent=2) + "\n", encoding="utf-8")

    args.md_out.parent.mkdir(parents=True, exist_ok=True)
    args.md_out.write_text(render_loc_table(report), encoding="utf-8")
    print(f"wrote {args.md_out}")

    args.swap_md_out.write_text(render_swap_md(swap), encoding="utf-8")
    print(f"wrote {args.swap_md_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
